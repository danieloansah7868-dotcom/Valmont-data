-- Website-build deposits are not data bundle orders. Service-role access only.
create table if not exists public.website_requests (
  id bigint generated by default as identity primary key,
  reference text not null unique,
  package text not null check (package in ('Starter', 'Popular', 'Auto-Sell')),
  amount numeric(12,2) not null check (amount > 0),
  customer_name text not null,
  phone text not null,
  business text not null,
  domain text not null default '',
  colours text not null,
  networks jsonb not null default '[]'::jsonb,
  features text not null default '',
  notes text not null default '',
  status text not null default 'initializing' check (status in ('initializing','awaiting_payment','checkout_unknown','paid','payment_review')),
  checkout_url text,
  provider_reference text unique,
  received_amount numeric(12,2),
  created_at timestamptz not null default now(),
  paid_at timestamptz
);
alter table public.website_requests enable row level security;
