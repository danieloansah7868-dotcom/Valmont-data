/* -------------------------------------------------------------------------- */
/* faq.html — hand-written page, generated schema                              */
/* --------------------------------------------------------------------------
   The FAQ page has ten real answers and no FAQPage markup, which is the one
   schema type Google still shows as a rich result for this kind of page.
   Rather than hand-writing JSON-LD that would quietly drift from the copy, we
   read the visible questions and answers back out of the file and generate the
   schema from them. Same trick for the size range, which had gone stale ("1GB
   to 50GB" while Telecel sells 100GB).
   -------------------------------------------------------------------------- */

const FAQ_START = "<!--SEO:FAQ_JSONLD:START";
const FAQ_END = "<!--SEO:FAQ_JSONLD:END-->";
const RANGE_START = "<!--SEO:SIZE_RANGE:START-->";
const RANGE_END = "<!--SEO:SIZE_RANGE:END-->";

/**
 * Locate a `<!--SEO:X:START ... --> ... <!--SEO:X:END-->` region.
 *
 * Throws instead of skipping: a missing END marker means the region cannot be
 * rewritten, and silently leaving yesterday's schema in the page is exactly the
 * drift this generator exists to prevent. (An earlier version dropped the END
 * marker while rewriting, which froze faq.html's FAQPage schema on its first
 * run — it kept saying "1GB to 50GB" while the visible copy said 100GB.)
 *
 * @returns {[number, number]} start index, end index (exclusive)
 */
function regionBounds(html, start, end, what) {
  const i = html.indexOf(start);
  const j = html.indexOf(end);
  if (i === -1 || j === -1 || j < i) {
    throw new Error(
      what + " is missing its SEO region marker (" + (i === -1 ? start : end) +
      ") — restore it, then re-run npm run seo:generate"
    );
  }
  return [i, j + end.length];
}

function stripTags(fragment) {
  return String(fragment)
    .replace(/<[^>]+>/g, " ")
    .replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&nbsp;/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function injectFaq(D) {
  const file = path.join(ROOT, "faq.html");
  if (!fs.existsSync(file)) return { questions: 0 };
  let html = fs.readFileSync(file, "utf8");

  /* 1. read the visible Q&A back out of the page */
  const qas = [];
  const re = /<button class="faq-q">([\s\S]*?)<span class="chev">[\s\S]*?<\/button>\s*<div class="faq-a">([\s\S]*?)<\/div>/g;
  let m;
  while ((m = re.exec(html))) {
    const q = stripTags(m[1]);
    const a = stripTags(m[2]);
    if (q && a) qas.push([q, a]);
  }

  /* 2. replace the marked block with schema built from exactly that text */
  const [i, jEnd] = regionBounds(html, FAQ_START, FAQ_END, "faq.html");
  if (qas.length) {
    const block =
      FAQ_START + " — " + qas.length + " questions read from the visible FAQ below -->\n  " +
      ldBlock(faqLd(qas)) + "\n  " + FAQ_END;
    html = html.slice(0, i) + block + html.slice(jEnd);
  }

  /* 3. the size-range sentence, derived from the live catalogue */
  const [ri, rjEnd] = regionBounds(html, RANGE_START, RANGE_END, "faq.html");
  {
    const sentence =
      "Bundle sizes run from " + K.sizeLabel(D.all.minSize) + " to " + K.sizeLabel(D.all.maxSize) +
      " — " + D.all.count + " bundles in total, from " + money(D.all.minPrice) + " to " + money(D.all.maxPrice) + ".";
    html = html.slice(0, ri) + RANGE_START + sentence + RANGE_END + html.slice(rjEnd);
  }

  fs.writeFileSync(file, html);
  return { questions: qas.length };
}

/* store.html — same trick: FAQPage generated from the visible <details> FAQ, so
   the schema can only ever say what the page actually says. */
const STORE_FAQ_START = "<!--SEO:STORE_FAQ_JSONLD:START";
const STORE_FAQ_END = "<!--SEO:STORE_FAQ_JSONLD:END-->";

function injectStoreFaq() {
  const file = path.join(ROOT, "store.html");
  if (!fs.existsSync(file)) return { questions: 0 };
  let html = fs.readFileSync(file, "utf8");

  const qas = [];
  const re = /<details class="seo-faq"[^>]*>\s*<summary>([\s\S]*?)<\/summary>\s*<div>([\s\S]*?)<\/div>\s*<\/details>/g;
  let m;
  while ((m = re.exec(html))) {
    const q = stripTags(m[1]);
    const a = stripTags(m[2]);
    if (q && a) qas.push([q, a]);
  }

  const [i, jEnd] = regionBounds(html, STORE_FAQ_START, STORE_FAQ_END, "store.html");
  if (qas.length) {
    const block =
      STORE_FAQ_START + " — " + qas.length + " questions read from the visible FAQ above -->\n      " +
      ldBlock(faqLd(qas)) + "\n      " + STORE_FAQ_END;
    html = html.slice(0, i) + block + html.slice(jEnd);
    fs.writeFileSync(file, html);
  }
  return { questions: qas.length };
}

