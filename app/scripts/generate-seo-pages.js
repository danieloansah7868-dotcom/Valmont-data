/* Sitemap — built from the pages we just wrote, plus the canonical of every    */
/* existing hand-written page (so <loc> is byte-identical to the canonical)     */
/* -------------------------------------------------------------------------- */

const HANDWRITTEN = [
  "index.html", "about.html", "contact.html", "faq.html", "store.html",
  "signup.html", "signin.html", "privacy.html", "terms.html",
  "status.html", "history.html", "dashboard.html", "admin.html",
  "autoreload.html", "otp.html", "offline.html", "storefront.html",
];

const HANDWRITTEN_PRIORITY = {
  "index.html": { priority: "1.0", changefreq: "daily" },
  "store.html": { priority: "0.7", changefreq: "monthly" },
  "about.html": { priority: "0.5", changefreq: "monthly" },
  "faq.html": { priority: "0.6", changefreq: "monthly" },
  "contact.html": { priority: "0.5", changefreq: "monthly" },
  "signup.html": { priority: "0.4", changefreq: "yearly" },
  "signin.html": { priority: "0.3", changefreq: "yearly" },
  "privacy.html": { priority: "0.2", changefreq: "yearly" },
  "terms.html": { priority: "0.2", changefreq: "yearly" },
};

function readPageMeta(file) {
  const html = fs.readFileSync(path.join(ROOT, file), "utf8");
  const canonical = (html.match(/<link[^>]+rel=["']canonical["'][^>]+href=["']([^"']+)["']/i) || [])[1] || null;
  const robots = (html.match(/<meta[^>]+name=["']robots["'][^>]+content=["']([^"']+)["']/i) || [])[1] || "";
  return { canonical, noindex: /noindex/i.test(robots), html };
}

function buildSitemap(warnings) {
  const urls = [];

  /* generated pages first — they are the commercial ones */
  for (const p of pages) {
    urls.push({
      loc: abs(p.canonicalPath),
      lastmod: TODAY,
      changefreq: p.changefreq,
      priority: p.priority.toFixed(1),
    });
  }

  /* then the hand-written pages, only if they canonicalise themselves and are
     not noindexed. Reading the canonical from the file is what guarantees the
     sitemap and the page can never disagree. */
  for (const file of HANDWRITTEN) {
    const full = path.join(ROOT, file);
    if (!fs.existsSync(full)) continue;
    const meta = readPageMeta(file);
    const cfg = HANDWRITTEN_PRIORITY[file] || { priority: "0.4", changefreq: "monthly" };
    if (meta.noindex) {
      warnings.push(file + " is noindex → left out of the sitemap");
      continue;
    }
    if (!meta.canonical) {
      warnings.push(file + " has no canonical → left out of the sitemap (fix the page, don't guess here)");
      continue;
    }
    urls.push({ loc: meta.canonical, lastmod: TODAY, changefreq: cfg.changefreq, priority: cfg.priority });
  }

  /* de-duplicate by loc, keep the highest priority */
  const byLoc = new Map();
  for (const u of urls) {
    const prev = byLoc.get(u.loc);
    if (!prev || parseFloat(u.priority) > parseFloat(prev.priority)) byLoc.set(u.loc, u);
  }
  const list = Array.from(byLoc.values()).sort((a, b) => parseFloat(b.priority) - parseFloat(a.priority) || a.loc.localeCompare(b.loc));

  const xml =
    '<?xml version="1.0" encoding="UTF-8"?>\n' +
    "<!-- " + GENERATED_MARK + " -->\n" +
    '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' +
    list
      .map(
        (u) =>
          "  <url>\n" +
          "    <loc>" + esc(u.loc) + "</loc>\n" +
          "    <lastmod>" + u.lastmod + "</lastmod>\n" +
          "    <changefreq>" + u.changefreq + "</changefreq>\n" +
          "    <priority>" + u.priority + "</priority>\n" +
          "  </url>"
      )
      .join("\n") +
    "\n</urlset>\n";

  fs.writeFileSync(path.join(ROOT, "sitemap.xml"), xml);
  return list;
}

