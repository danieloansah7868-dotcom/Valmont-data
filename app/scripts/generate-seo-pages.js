/* --------------------------------------------------------------------------
   The homepage head used to be hand-written with numbers baked in ("24 bundles
   from GH₵4.00") and a 69-character title that Google truncates mid-word. Both
   problems are the same problem: a human maintaining a string that the data
   already knows. So the head is generated between markers, from the same
   catalogue object the pages are built from, and `fit()` keeps every string
   inside the length Google actually displays.
   -------------------------------------------------------------------------- */
const HEAD_START = "<!--SEO:HOME_HEAD:START";
const HEAD_END = "<!--SEO:HOME_HEAD:END-->";

/** First candidate that fits the budget (titles ~62ch, descriptions ~160ch). */
function fit(candidates, max) {
  for (const c of candidates) if (c.length <= max) return c;
  return candidates[candidates.length - 1].slice(0, max);
}

/** "MTN, Telecel and AirtelTigo" — derived, never typed out. */
function joinList(xs) {
  if (!xs.length) return "";
  if (xs.length === 1) return xs[0];
  return xs.slice(0, -1).join(", ") + " and " + xs[xs.length - 1];
}

