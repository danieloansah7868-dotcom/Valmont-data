/* Display order for networks: the order the storefront tabs and the DB seed use.
   (Alphabetical would put AirtelTigo first, which is not how the business
   talks about its own catalogue.) */
const NET_ORDER = ["mtn", "telecel", "airteltigo"];
const byNetworkOrder = (a, b) =>
  (NET_ORDER.indexOf(a.network) - NET_ORDER.indexOf(b.network)) || a.size_mb - b.size_mb;

const money = (n) => K.SITE.currencySymbol + Number(n).toFixed(2);
const perGb = (n) => K.SITE.currencySymbol + Number(n).toFixed(2) + " per GB";
const esc = (s) =>
  String(s == null ? "" : s)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
const abs = (p) => ORIGIN + (p.startsWith("/") ? p : "/" + p);

function stats(items) {
  const prices = items.map((i) => i.price);
  const sizes = items.map((i) => i.size_mb);
  const cheapest = items.reduce((a, b) => (b.price < a.price ? b : a), items[0]);
  const dearest = items.reduce((a, b) => (b.price > a.price ? b : a), items[0]);
  const smallest = items.reduce((a, b) => (b.size_mb < a.size_mb ? b : a), items[0]);
  const largest = items.reduce((a, b) => (b.size_mb > a.size_mb ? b : a), items[0]);
  const bestValue = items.reduce((a, b) => (b.per_gb < a.per_gb ? b : a), items[0]);
  return {
    count: items.length,
    minPrice: Math.min(...prices),
    maxPrice: Math.max(...prices),
    minSize: Math.min(...sizes),
    maxSize: Math.max(...sizes),
    cheapest, dearest, smallest, largest, bestValue,
  };
}

function derive(items) {
  const byNetwork = {};
  for (const code of ["mtn", "telecel", "airteltigo"]) {
    const list = items.filter((i) => i.network === code);
    if (list.length) byNetwork[code] = { items: list, stats: stats(list) };
  }
  const all = stats(items);
  const cheap = items.filter((i) => i.price <= CHEAP_MAX_CEDIS).sort((a, b) => a.price - b.price);
  const big = items.filter((i) => i.size_mb >= BIG_MIN_MB).sort((a, b) => b.size_mb - a.size_mb);
  const rollover = items.filter((i) => !!i.validity_days);
  const nonExpiry = items.filter((i) => !i.validity_days);
  return { byNetwork, all, cheap, big, rollover, nonExpiry };
}

/** Prefix list for a network, straight out of lib/phones.js (no invention). */
function prefixList(code) {
  return (phones.NETWORK_PREFIXES[code] || []).map((p) => "0" + p);
}
/** Prefixes that more than one network claims — we say so openly. */
function sharedPrefixes() {
  const seen = {};
  for (const [code, list] of Object.entries(phones.NETWORK_PREFIXES)) {
    for (const p of list) (seen["0" + p] = seen["0" + p] || []).push(code);
  }
  return Object.entries(seen).filter(([, codes]) => codes.length > 1);
}

