function writePages() {
  let written = 0;
  for (const p of pages) {
    const full = path.join(ROOT, p.file);
    fs.mkdirSync(path.dirname(full), { recursive: true });
    fs.writeFileSync(full, p.html);
    p.bytes = Buffer.byteLength(p.html);
    p.words = countWords(p.html);
    written++;
  }
  return written;
}

function countWords(html) {
  const body = html.replace(/^[\s\S]*?<main>/, "").replace(/<\/main>[\s\S]*$/, "");
  const noScripts = body.replace(/<script[\s\S]*?<\/script>/g, " ").replace(/<style[\s\S]*?<\/style>/g, " ");
  const text = noScripts.replace(/<[^>]+>/g, " ").replace(/&[a-z#0-9]+;/gi, " ").replace(/\s+/g, " ").trim();
  return text.split(" ").filter(Boolean).length;
}

