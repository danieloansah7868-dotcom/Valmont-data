/** Visible "also searched as" line — the words that actually rank are visible. */
function alsoSearchedAs(catIds, extra) {
  const words = K.alsoSearchedAs(catIds, 14).concat(extra || []);
  const seen = new Set();
  const list = words.filter((w) => (seen.has(w.toLowerCase()) ? false : (seen.add(w.toLowerCase()), true))).slice(0, 14);
  return `    <p class="seo-aka"><span>Also searched as:</span> ${list.map((w) => "<span>" + esc(w) + "</span>").join(" ")}</p>`;
}

/**
 * Price table — real rows only. `highlight` marks the current product.
 * Columns are the ones a buyer compares: size, validity, price, price per GB.
 */
function priceTable(items, opts) {
  const o = opts || {};
  const rows = items
    .map((it) => {
      const hl = o.highlight && o.highlight.network === it.network && o.highlight.size_mb === it.size_mb;
      const buy = "/?net=" + it.network + "&size=" + it.size_mb + "#buy";
      return `        <tr${hl ? ' class="on"' : ""}>
          <td>${o.showNetwork ? "<b>" + esc(it.network_name) + "</b> " : ""}${esc(it.size_label)}</td>
          <td>${esc(it.validity_label)}</td>
          <td><b>${money(it.price)}</b></td>
          <td>${money(it.per_gb)}</td>
          <td>${o.linkSizes ? '<a href="' + it.url + '">' + esc(it.size_label) + " details</a>" : '<a class="btn btn-sm btn-orange" href="' + buy + '">Buy</a>'}</td>
        </tr>`;
    })
    .join("\n");
  const caption = o.caption ? '<caption class="seo-table-caption">' + esc(o.caption) + "</caption>" : "";
  return `    <div class="table-wrap seo-table">
      <table>
        ${caption}
        <thead>
          <tr><th scope="col">${o.showNetwork ? "Bundle" : "Size"}</th><th scope="col">Validity</th><th scope="col">Price</th><th scope="col">Per GB</th><th scope="col">${o.linkSizes ? "More" : "Buy"}</th></tr>
        </thead>
        <tbody>
${rows}
        </tbody>
      </table>
    </div>`;
}

