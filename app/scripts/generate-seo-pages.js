/* Pull the visible FAQ back out of the rendered body so the JSON-LD can only
   ever declare questions and answers that are literally on the page. */
function extractFaqs(page, body) {
  const out = [];
  const re = /<details class="seo-faq-item"[^>]*>\s*<summary>([\s\S]*?)<\/summary>\s*<div>([\s\S]*?)<\/div>\s*<\/details>/g;
  let m;
  while ((m = re.exec(body))) {
    const q = unesc(m[1].trim());
    const a = unesc(m[2].replace(/<\/?p>/g, " ").replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim());
    out.push([q, a]);
  }
  return out;
}
function unesc(s) {
  return String(s)
    .replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'").replace(/&amp;/g, "&");
}

