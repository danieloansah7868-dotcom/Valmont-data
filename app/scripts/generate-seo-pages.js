/* Drift check: do the published pages still match the live catalogue?         */
/* -------------------------------------------------------------------------- */

async function checkDrift(catalogue) {
  const problems = [];
  if (!catalogue.items.length) return ["no catalogue loaded"];
  for (const item of catalogue.items) {
    const file = path.join(ROOT, item.url);
    if (!fs.existsSync(file)) {
      problems.push(item.network + " " + item.size_label + " → page missing (" + item.url + ") — run npm run seo:generate");
      continue;
    }
    const html = fs.readFileSync(file, "utf8");
    const published = (html.match(/<dt>Price<\/dt><dd><b>([^<]+)<\/b>/) || [])[1];
    if (published && published !== money(item.price)) {
      problems.push(item.network + " " + item.size_label + " → published " + published + " but live price is " + money(item.price));
    }
  }
  /* every page that exists on disk should still be in the catalogue */
  const dir = path.join(ROOT, "bundles");
  if (fs.existsSync(dir)) {
    for (const net of fs.readdirSync(dir)) {
      const netDir = path.join(dir, net);
      if (!fs.statSync(netDir).isDirectory()) continue;
      for (const f of fs.readdirSync(netDir)) {
        if (!f.endsWith(".html")) continue;
        const url = "/bundles/" + net + "/" + f;
        if (!catalogue.items.some((i) => i.url === url)) problems.push(url + " exists but is not in the live catalogue — stale page, re-run the generator");
      }
    }
  }
  return problems;
}

