function fetchJson(url, timeoutMs = 4000) {
  return new Promise((resolve, reject) => {
    const lib = url.startsWith("https") ? https : http;
    const req = lib.get(url, { headers: { Accept: "application/json" } }, (res) => {
      let body = "";
      res.on("data", (c) => (body += c));
      res.on("end", () => {
        if (res.statusCode !== 200) return reject(new Error(url + " → HTTP " + res.statusCode));
        try { resolve(JSON.parse(body)); } catch (e) { reject(e); }
      });
    });
    req.on("error", reject);
    req.setTimeout(timeoutMs, () => req.destroy(new Error(url + " → timeout")));
  });
}

/**
 * @returns {Promise<{source:string, networks:Array, items:Array}>}
 * items: { network, network_name, size_mb, size_label, size_slug, validity_days,
 *          price, per_gb, url, id?, available? }
 */
async function loadCatalogue() {
  let rows = null;
  let source = "seed (lib/demo-data.js — mirror of supabase/schema.sql)";

  if (WANT_API) {
    try {
      const data = await fetchJson(API_BASE + "/api/bundles");
      rows = data.bundles.map((b) => ({
        network: b.network,
        size_mb: b.size_mb,
        validity_days: b.validity_days,
        price: Number(b.price),
        id: b.id,
        available: b.available !== false,
      }));
      source = "live API (" + API_BASE + "/api/bundles)";
    } catch (e) {
      if (flagValue("api", null) || process.env.SEO_API) throw new Error("--api requested but unreachable: " + e.message);
      log("  ! live catalogue unreachable (" + e.message + ") — falling back to the seed file");
    }
  }

  if (!rows) {
    rows = BUNDLES.map((b) => ({
      network: b.network,
      size_mb: b.size_mb,
      validity_days: b.validity_days === undefined ? null : b.validity_days,
      price: Number(b.sell),
      available: null, // seed has no float information — never publish a stock claim
    }));
  }

  const NETWORK_NAMES = { mtn: "MTN", telecel: "Telecel", airteltigo: "AirtelTigo" };
  const items = rows
    .filter((r) => r.size_mb > 0 && isFinite(r.price))
    .map((r) => {
      const size_label = K.sizeLabel(r.size_mb);
      return Object.assign({}, r, {
        network_name: NETWORK_NAMES[r.network] || r.network,
        size_label,
        size_slug: K.sizeSlug(r.size_mb),
        per_gb: r.price / (r.size_mb / 1024),
        url: "/bundles/" + r.network + "/" + K.sizeSlug(r.size_mb) + ".html",
        validity_label: r.validity_days ? r.validity_days + "-day rollover" : "No expiry",
        keywords: K.itemKeywords(r),
      });
    })
    .sort((a, b) => a.network.localeCompare(b.network) || a.size_mb - b.size_mb);

  const networks = ["mtn", "telecel", "airteltigo"]
    .filter((code) => items.some((i) => i.network === code))
    .map((code) => ({ code, name: NETWORK_NAMES[code] }));

  return { source, networks, items };
}

