#!/usr/bin/env node
/* ============================================================================
   scripts/generate-seo-pages.js — renders every indexable catalogue/service
   landing page, plus sitemap.xml, from the REAL catalogue. Zero dependencies,
   no build step for the site itself: this writes plain .html files that Vercel
   serves statically, exactly like the hand-written pages.

     npm run seo:generate                    # from the seed in lib/demo-data.js
     npm run seo:generate -- --api           # from a running server (live prices)
     npm run seo:generate -- --api=http://localhost:8787
     npm run seo:check                       # fail if live prices ≠ published pages

   Why it exists
   -------------
   Before this script the whole catalogue lived in one page (`/`) rendered by
   JavaScript from GET /api/bundles. A crawler saw <div id="bundleGrid">Loading
   bundles…</div> and not one price, not one size, not one network name. There
   was no URL for "MTN data", "non expiry data" or "100gb bundle" at all.

   Everything here is derived: counts, price ranges, price-per-GB, "best value"
   claims, the tier slices, the size tables and the meta descriptions all come
   from the catalogue rows. No number is hardcoded, so nothing can drift into a
   lie in the SERP — and `--check` proves it in CI.

   What we deliberately DO NOT generate
   ------------------------------------
   • City pages ("data bundles in Kumasi"). A bundle is credited to a Ghanaian
     MSISDN seconds after payment: coverage, price and turnaround are identical
     everywhere in the country, so a city page could only repeat the national
     one. That is the doorway-page pattern. See LOCATIONS in lib/keywords.js.
   • A separate "non-expiry" page. Every non-expiry bundle we stock is MTN, so
     it would be a byte-for-byte duplicate of /bundles/mtn.html. The MTN page
     IS the non-expiry page (it says so, and owns that vocabulary).
   • Reviews, ratings, stock claims, delivery-time promises or customer counts.
     We have no such data, so no such schema or copy.
   ============================================================================ */

